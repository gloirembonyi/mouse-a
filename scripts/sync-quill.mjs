#!/usr/bin/env node
// Kudu Quill's engines have ONE source of truth in Kudu Core (../backend-Thothai/src/lib): the rule
// engine (grammar-rules.js), the spelling core (spell-core.js) and the en_US dictionary
// (dictionary-en). The browser extension and this app both run them locally, so spelling and grammar
// give the same answers offline as they do online. Run `npm run sync:quill` after changing either.
//
// The sources are UMD; Vite wants ES modules, so each is wrapped (a local `module` makes the UMD
// header take its CommonJS branch) and exported as the default. The output is committed on purpose:
// building the app must not depend on the sibling repo being checked out.
import { copyFileSync, existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const backend = resolve(here, "..", "..", "backend-Thothai");
const out = resolve(here, "..", "frontend", "src", "lib", "quill");
const vendor = resolve(out, "vendor");
const dict = resolve(out, "dict");

const need = (p) => {
  if (!existsSync(p)) {
    console.error(`Not found: ${p}\nCheck out backend-Thothai next to this repo (and run npm install there for the dictionary).`);
    process.exit(1);
  }
  return p;
};

mkdirSync(vendor, { recursive: true });
mkdirSync(dict, { recursive: true });

for (const name of ["grammar-rules", "spell-core"]) {
  const src = readFileSync(need(resolve(backend, "src", "lib", `${name}.js`)), "utf8");
  const banner = `// GENERATED by scripts/sync-quill.mjs from backend-Thothai/src/lib/${name}.js - do not edit; edit the backend copy and re-run \`npm run sync:quill\`.\n`;
  writeFileSync(resolve(vendor, `${name}.js`), `${banner}const module = { exports: {} };\n${src}\nexport default module.exports;\n`);
  console.log(`✓ vendor/${name}.js (${statSync(resolve(vendor, `${name}.js`)).size} bytes)`);
}

const dictSrc = resolve(backend, "node_modules", "dictionary-en");
for (const [from, to] of [["index.aff", "en.aff"], ["index.dic", "en.dic"]]) {
  copyFileSync(need(resolve(dictSrc, from)), resolve(dict, to));
  console.log(`✓ dict/${to} (${statSync(resolve(dict, to)).size} bytes)`);
}
